  def generate_dockerignore
    return unless @repo_path

    ignore_path = File.join(app_path, ".dockerignore")
    return if File.exist?(ignore_path)

    File.write(ignore_path, dockerignore_content)
  end

  COMMON_IGNORES = %w[
    .git .github .gitlab-ci.yml .circleci .dockerignore Dockerfile* docker-compose*.yml compose*.yml
    .env .env.* !.env.example !.env.sample .DS_Store *.log .idea .vscode coverage
  ].freeze

  FRAMEWORK_IGNORES = {
    "rails"  => %w[/log/* /tmp/* !/log/.keep !/tmp/.keep /storage/* /public/assets /node_modules
                   /vendor/bundle /.bundle /config/master.key /config/credentials/*.key /app/assets/builds/*],
    "node"   => %w[node_modules .next .nuxt .output .turbo npm-debug.log* yarn-error.log*],
    "nextjs" => %w[node_modules .next out .turbo npm-debug.log* yarn-error.log*],
    "bun"    => %w[node_modules .turbo],
    "python" => %w[__pycache__ *.py[cod] .venv venv .pytest_cache .mypy_cache .ruff_cache .tox *.egg-info],
    "go"     => %w[/bin vendor],
    "elixir" => %w[_build deps .elixir_ls],
    "static" => %w[node_modules]
  }.freeze

  def dockerignore_content
    family = case @detection.framework
    when "fastapi", "flask", "django", "python" then "python"
    else @detection.framework.to_s
    end
    extra = FRAMEWORK_IGNORES.fetch(family, [])
    extra += %w[dist build] if family == "static" && m("build_tool")

    lines = [ "# Generated by Anchor — keeps secrets and local artifacts out of the build context." ]
    lines += COMMON_IGNORES
    lines += extra
    lines.join("\n") + "\n"
  end
